/**
 * 場の光。
 *
 * **平行光と半球光は、平らな面の上では明るさが一定になる**（法線が一定なので）。
 * 隠れ場所は板と箱でできているので、この2つだけだと面が単色に塗りつぶされ、
 * 面の境目でしか明るさが変わらない（baseline 実測: はこ・とびら・ふとん・
 * すいめん・こや で内部の L\* の四分位範囲が 0.00〜0.35）。
 */
export const LIGHTS = {
  /** 上からの主光。**顔と目が見えることが最重要**（§4-4）なので少し手前から */
  key: { color: 0xfff3e2, intensity: 1.6, position: [0.4, 1.2, 1.0] as const },
  /** 空と地の色。全体の底上げ */
  hemi: { sky: 0xdceeff, ground: 0x4a4436, intensity: 1.1 },
};

/**
 * 隠れ場所に焼き込む陰影（頂点カラー）。
 *
 * 平らな面に明るさの傾きを作るのは、光を足しても届かない
 * （平行光・半球光は面の上で一定、点光源は面1枚の中では数%しか変わらない）。
 * **絵の描き手がやるのと同じことを、頂点の色でやる。**
 *
 * - `lift` … 上を明るく、下を暗く（掛ける値の幅）
 * - `depth` … 奥ほど暗く。箱の内側やふたの裏が沈んで、奥行きが出る
 *
 * **隠れ場所ぜんぶを1つの箱として測ってから塗る。** メッシュごとに測ると、
 * たまごの殻とふたのように「同じ形を2つに割ったもの」で
 * 傾きが割れ目でリセットされ、段差が出る。
 */
export const FORM_SHADING = {
  lift: 0.30,
  depth: 0.18,
};

/**
 * 模様を貼る細かさ（ワールド座標で、テクスチャ1枚ぶんの大きさ）。
 *
 * 隠れ場所は幅 1.70・高さ 1.35 なので、1.2 だと横に 1.4 回ぶん。
 * 小さくすると模様が細かくなり、遠目には無地に戻る。
 */
export const SURFACE_TILE = 0.85;

/**
 * 落ち影（`Backdrop.createContactShadow`）。
 *
 * **本体の外接箱から大きさを決める。** 以前は `mouthWidth × 1.9`・
 * 高さはその 0.62倍という決め打ちで、形の違う隠れ場所に寸法のほぼ同じ
 * 楕円が付いていた（判定の実測: うえきばちで幅 2.15倍）。
 *
 * ずらす向きは、主光（`LIGHTS.key` が左上手前）と逆の右下。
 * **離しすぎないこと。** 物理どおりに（仰角 50° / 奥行き 1.45）計算すると
 * 左下へ 1.76 も動いて、影が本体から切り離れて見える。
 */
export const DROP_SHADOW = {
  /**
   * ぼかしの幅（ワールド）。**倍率ではなく足し算で持つ。**
   *
   * 倍率 1.06 でやったら、影が本体の真後ろに隠れて**1画素も見えなくなった**
   * （実測: 接地の暗さ V5 が 29箇所中 24箇所で 0.0〜0.5 に落ちた）。
   * 影の芯は本体と同じ大きさで、そのまわりにこの幅だけ滲む、が正しい。
   */
  blur: 0.18,
  /** 本体の中心からずらす量。主光（左上手前）と逆の右下 */
  offsetX: 0.14,
  offsetY: -0.16,
  /** 隠れ場所より奥。手前に出すと動物の足元に黒い帯が乗る */
  z: -0.34,
};
